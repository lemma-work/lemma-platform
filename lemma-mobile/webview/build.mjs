/* Build the pages the phone app runs inside WebViews, each into one HTML
   string the app imports (`*.generated.ts`, beside the area that shows it):

   - the page editor: the web's own `document-editor.tsx` and its extensions,
     from `lemma-frontend/src`, with the few modules that reach the network or
     the desktop shell swapped for the phone's bridge (`src/editor/shim`);
   - a PDF reader: pdf.js, which Android's WebView needs to show a PDF at all;
   - the agent's screen: noVNC, fed by a socket the app holds (`src/vnc`);
   - a call's sound: the microphone and the speaker, with PCM to and from
     the call's socket, which the app holds (`src/call`).

   Run `npm ci && npm run build` here after the web's editor changes, or
   `npm run build -- vnc call` for one page. The generated files record a hash of
   every input, and the app's tests fail when one is stale. */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const mobile = resolve(here, "..");
const web = resolve(mobile, "../lemma-frontend/src");
const FILES = resolve(mobile, "src/areas/files/web");
const MORE = resolve(mobile, "src/areas/more");

/** The pages asked for (`npm run build -- vnc`), or all of them. */
const asked = process.argv.slice(2);
const wanted = (page) => asked.length === 0 || asked.includes(page);

/** Web modules the phone replaces. Everything else under `@/` is the web's own file. */
const SHIMS = {
    "@/data": "src/editor/shim/data.ts",
    "@/session/client": "src/editor/shim/client.ts",
    "@tiptap/react/menus": "src/editor/shim/menus.tsx",
    "@tiptap/extension-drag-handle-react": "src/editor/shim/drag-handle.tsx",
};

function webModule(path) {
    for (const ending of ["", ".ts", ".tsx", "/index.ts", "/index.tsx"]) {
        try {
            readFileSync(path + ending);
            return path + ending;
        } catch {
            /* try the next */
        }
    }
    return null;
}

const aliases = {
    name: "phone-aliases",
    setup(build) {
        build.onResolve({ filter: /^(@\/|@web\/|@tiptap\/react\/menus$|@tiptap\/extension-drag-handle-react$)/ }, (args) => {
            if (SHIMS[args.path] && !args.importer.includes("/src/editor/shim/")) return { path: resolve(here, SHIMS[args.path]) };
            /* The app's own modules name the web's as `@web/` (`web-imports.js`). */
            const within = args.path.startsWith("@web/") ? args.path.slice(5) : args.path.startsWith("@/") ? args.path.slice(2) : null;
            if (within === null) return undefined;
            const found = webModule(join(web, within));
            if (!found) return { errors: [{ text: "No web module " + args.path }] };
            return { path: found };
        });
        /* A package a web file imports comes from here, never from a
           node_modules the web may have of its own: one React, one TipTap. */
        build.onResolve({ filter: /^[^./]/ }, (args) => {
            if (!args.importer.startsWith(web) || args.pluginData === "here") return undefined;
            return build.resolve(args.path, { resolveDir: here, kind: args.kind, pluginData: "here" });
        });
    },
};

function fontFace(file, weight) {
    const bytes = readFileSync(resolve(mobile, "node_modules/@expo-google-fonts/albert-sans", file));
    return `@font-face{font-family:"Albert Sans";font-weight:${weight};font-style:normal;font-display:block;src:url(data:font/ttf;base64,${bytes.toString("base64")}) format("truetype")}`;
}

/** The inputs a page was built from, hashed, so a stale build is caught. */
function stamp(inputs) {
    const hash = createHash("sha256");
    for (const file of [...inputs].sort()) {
        hash.update(file + "\0");
        hash.update(readFileSync(resolve(mobile, file)));
    }
    return hash.digest("hex").slice(0, 16);
}

function emit(out, name, html, inputs) {
    const files = [...inputs].map((file) => relative(mobile, resolve(here, file))).filter((file) => !file.includes("node_modules")).sort();
    const body = `/* Generated by lemma-mobile/webview/build.mjs. Do not edit: change the
   sources and run \`npm run build\` in lemma-mobile/webview. */

export const INPUTS: string[] = ${JSON.stringify(files, null, 4)};

export const STAMP = ${JSON.stringify(stamp(files))};

export const HTML = ${JSON.stringify(html)};
`;
    writeFileSync(join(out, name), body);
    console.log(name, Math.round(html.length / 1024) + " KB", files.length + " inputs");
}

async function bundle(entry, options = {}) {
    const result = await esbuild.build({
        entryPoints: [resolve(here, entry)],
        bundle: true,
        write: false,
        minify: true,
        format: "iife",
        target: ["chrome90", "safari15"],
        platform: "browser",
        jsx: "automatic",
        nodePaths: [resolve(here, "node_modules")],
        define: { "process.env.NODE_ENV": '"production"' },
        loader: { ".css": "css" },
        outdir: "out",
        metafile: true,
        legalComments: "none",
        logLevel: "warning",
        plugins: [aliases],
        ...options,
    });
    if (process.env.ANALYZE) console.log(await esbuild.analyzeMetafile(result.metafile, { verbose: false }));
    const js = result.outputFiles.find((file) => file.path.endsWith(".js"))?.text ?? "";
    const css = result.outputFiles.find((file) => file.path.endsWith(".css"))?.text ?? "";
    return { js, css, inputs: Object.keys(result.metafile.inputs) };
}

/* Closing tags inside a script would end it early. */
const safe = (js) => js.replace(/<\/(script)/gi, "<\\/$1");

if (wanted("editor")) {
const editor = await bundle("src/editor/main.tsx");
emit(FILES, "editor-page.generated.ts", `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover"><style>${fontFace("400Regular/AlbertSans_400Regular.ttf", 400)}${fontFace("500Medium/AlbertSans_500Medium.ttf", 500)}${editor.css}</style></head><body><div id="root"></div><script>${safe(editor.js)}</script></body></html>`, [...editor.inputs, "package-lock.json"]);

}

if (wanted("pdf")) {
const worker = readFileSync(resolve(here, "node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs"), "utf8");
const reader = await bundle("src/pdf/main.ts", { format: "esm", define: { "process.env.NODE_ENV": '"production"', PDF_WORKER_SOURCE: JSON.stringify(worker) } });
emit(FILES, "pdf-page.generated.ts", `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=5"><style>${reader.css}</style></head><body><div id="pages"></div><script type="module">${safe(reader.js)}</script></body></html>`, [...reader.inputs, "package-lock.json"]);
}

/* A page of the app's own, in the app's two faces, with nothing it could
   reach the API by: what it shows comes over the bridge. */
function own(entry) {
    return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,viewport-fit=cover"><style>${fontFace("400Regular/AlbertSans_400Regular.ttf", 400)}${fontFace("500Medium/AlbertSans_500Medium.ttf", 500)}${entry.css}</style></head><body><div id="root"></div><script>${safe(entry.js)}</script></body></html>`;
}

if (wanted("vnc")) {
    const screen = await bundle("src/vnc/main.ts", { format: "esm" });
    emit(resolve(MORE, "computer"), "vnc-page.generated.ts", own(screen).replace("<script>", '<script type="module">'), [...screen.inputs, "package-lock.json"]);
}

if (wanted("call")) {
    const sound = await bundle("src/call/main.ts");
    emit(resolve(MORE, "call"), "call-page.generated.ts", own(sound), [...sound.inputs, "package-lock.json"]);
}
